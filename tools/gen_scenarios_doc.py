#!/usr/bin/env python3
"""Regenerate docs/SCENARIOS.md from foresight_safety/tasks.py: python3 tools/gen_scenarios_doc.py"""
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from foresight_safety.taxonomy import SAFE_CORE_SUITES  # noqa: E402
from foresight_safety.tasks import DEFAULTS, DIAGNOSTIC_SUBSET, TASKS  # noqa: E402

OPS = {"hazard_injection": "HI", "constraint_tightening": "CT", "temporal_precondition": "TP"}


def main():
    counts = Counter(t.suite for t in TASKS.values())
    lines = [
        "# The 66 base scenarios",
        "",
        "Generated by `tools/gen_scenarios_doc.py` from `foresight_safety/tasks.py`; do not edit by hand.",
        "",
        "Every scenario is a RoboTwin task class `envs/<name>.py` with `task_config/<name>.yml` and",
        "`description/task_instruction/<name>.json`. *Template* scenarios wrap an upstream RoboTwin task with",
        "a generic safety layer (`SAFETY_TYPE` Collision / Fragile / Thermal / Spill); *composed* scenarios",
        "are hand-written task classes. Operators (paper Sec. III-B): HI hazard injection, CT constraint tightening,",
        "TP temporal precondition insertion. The per-scenario list and per-suite counts are not specified in the",
        "paper; the suite of each scenario is the category of the constraint its code checks",
        "(see docs/PAPER_ALIGNMENT.md).",
        "",
        "| Safe-Core suite | Scenarios |",
        "|---|---:|",
    ]
    for s in SAFE_CORE_SUITES:
        lines.append(f"| {s} | {counts[s]} |")
    lines += [f"| Total | {len(TASKS)} |", "",
              "Channels present in every scenario: `force` (contact force on task objects, "
              f"{DEFAULTS['f_max']} N; {DEFAULTS['f_max_fragile']} N for fragile/gentle scenarios), `table_edge` "
              f"(table-edge geofence, {DEFAULTS['table_margin']} m; omitted where objects leave the table by design), "
              "`distractor_clearance` and `distractor_displacement` (active only when distractors exist, i.e. at "
              "structure levels L1/L2). Template scenarios add `impact_speed` (scenario constant MAX_CONTACT_SPEED).",
              "", "The ten scenarios of the L/W/V diagnostics (two per suite) are marked with *.", ""]
    for s in SAFE_CORE_SUITES:
        lines += [f"## {s}", "", "| # | Scenario | Built from | Kind | Ops | Task-specific channels | Demo config |",
                  "|---:|---|---|---|---|---|---|"]
        rows = sorted((n, t) for n, t in TASKS.items() if t.suite == s)
        common = {"force", "table_edge", "distractor_clearance", "distractor_displacement", "impact_speed"}
        for i, (n, t) in enumerate(rows, 1):
            extra = [f"`{c.name}`" for c in t.channels if c.name not in common]
            star = "*" if n in DIAGNOSTIC_SUBSET else ""
            lines.append(f"| {i} | `{n}`{star} | `{t.base}` | {t.kind} | {'+'.join(OPS[o] for o in t.operators)} | "
                         f"{', '.join(extra) or '-'} | `{t.collect_config}` |")
        lines.append("")
    lines += ["## Channel definitions", "", "| Scenario | Channel | Category | eps | Definition |", "|---|---|---|---:|---|"]
    for n, t in sorted(TASKS.items()):
        for c in t.channels:
            if c.name in ("force", "table_edge", "distractor_clearance", "distractor_displacement"):
                continue
            lines.append(f"| `{n}` | `{c.name}` | {c.category} | {c.eps:g} | {c.doc} |")
    (ROOT / "docs" / "SCENARIOS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("docs/SCENARIOS.md written")


if __name__ == "__main__":
    main()
